L_MEM_ACC = 2
L_ROT = 1
L_ARRAY = 6
L_DRAIN_V2 = 8      # V2: 8 drain columns per tile
L_QPARAM = 2
L_RQ = 6
L_POOL = 2
L_RETIRE = 1
C_PIPE_V2 = (L_LOAD + L_ISSUE + L_MEM_ACC + L_ROT + L_ARRAY + (L_DRAIN_V2 - 1)
             + L_QPARAM + L_RQ + L_POOL + L_RETIRE)          # = 29
C_START_V2 = 3
C_DONE_V2 = 0

CLOCKS_MHZ = (249.9975, 333.33)    # V3 D2: PLL-reachable PL clocks

MODES_OS_ONLY = ("os",)
MODES_BEST = ("os", "splitk", "dw")

