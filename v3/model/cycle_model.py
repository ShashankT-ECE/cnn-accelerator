"""V3 parameterized cycle model (Phase 0 DSE; every number it produces is labelled "model").

Generalizes the V2 output-stationary (OS) cycle model to an R x C array:
R rows = output positions, C columns = output channels, one reduction step k per cycle
(k order (ic*KH + kh)*KW + kw, kw innermost, as in V2 ARCH_SPEC).

V2 basis (constants copied from v2/model/gos_cycle_model.py @ 28dd2ad; the N-generalisation of the
drain from v2/analysis/projection_16x16.py @ 28dd2ad):

    T          = ceil(OC/8) * OH * ceil(OW/8)
    LAYER_CYC  = T*K + C_PIPE            C_PIPE = 29 (RTL-derived, V2 D12)
    TOTAL_CYC  = sum(LAYER_CYC) + C_START(3) + C_DONE(0)

V3 generalization (all PROJECTED, not RTL-derived; each choice is a named parameter of ArrayConfig and
an assumption Pn in ASSUMPTIONS / v3/analysis/DSE_NOTES.md - these are candidate architecture choices,
not facts):

  * tile schedule. A tile issues `issue` cycles; the drain of tile i (D cycles) overlaps the issue of
    tile i+1 and the next tile's accumulators can only be copied to the shadow once the shadow is free,
    so consecutive tiles are spaced by max(issue, D):
        LAYER_CYC = issue_0 + sum_{i>=1} max(issue_i, D) + C_PIPE(D)
    With issue >= D for every tile this is exactly T*K + C_PIPE (the V2 model).
  * drain. V2 copies the accumulators to a shadow register and drains ONE COLUMN per cycle
    (one output channel x 8 pixels, ARCH_SPEC "Drain"); a column holds the R positions of one output
    channel, so D = C cycles and the requant needs R lanes (one channel's qparams per drain cycle).
    C_PIPE(D) = C_PIPE_V2 - (L_DRAIN - 1) + (D - 1)   (as projection_16x16.py, P1 there).
"""
from __future__ import annotations

import math
from dataclasses import dataclass, replace
from typing import Iterable, Sequence

import numpy as np

