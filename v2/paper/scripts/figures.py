# B2: latency vs clock
# --------------------------------------------------------------------------------------------
def fig_b2(c: FCtx) -> Artifact:
    """B2 clock sweep: (a) PL latency, (b) SOM-rail dP (INA260), (c) energy/image; x = pl_clk0."""
    art = c.art("fig_b2_clock")
    vs = impl_variants(art)
    data = {net: a3_net(art, net) for net in NETS}
    hwr = [r for r in (art.rows("hw_b2_clock.csv", hw=True) or []) if not r.get("skipped_reason")
           and r.get("latency_us")]
    ents = [e for e in power_summaries(art, "hw_b2_power_ina260") if e["clock"]]
    fig, axs = plt.subplots(1, 3, figsize=(COL_W, 1.95), sharex=True, layout="constrained")
    rows = []
    mk = {"lenet5": "o", "cifar10": "s"}
    ls = {"lenet5": "-", "cifar10": "--"}
    ax = axs[0]
    for net in NETS:
        d = data[net]
        if d and d[-1]["is_total"] and d[-1]["rtl"] is not None and vs:
            tot = d[-1]["rtl"]
            pts = [(fnum(r["pl_clk0_mhz_actual"]), div(tot, at(r, "pl_clk0_mhz_actual"), "cycles/MHz")) for r in vs]
            ax.plot([p[0] for p in pts], [p[1].value for p in pts], marker=mk[net], ls="none", mfc="white",
                    mec="0.35", ms=4, mew=0.7, zorder=4, label=f"{NET_TITLE[net]} RTL-sim cycles / post-impl f")
            rows += [{"panel": "latency", "net": net, "clock_mhz": f, "value": v.value, "unit": "us",
                      "kind": "rtl_sim_cycles/post_impl_clock", "src": v.origin} for f, v in pts]
        hn = sorted([r for r in hwr if r["net"] == net], key=lambda r: fnum(r["clock_readback_mhz"]))
        if hn:
            ax.plot([fnum(r["clock_readback_mhz"]) for r in hn], [fnum(r["latency_us"]) for r in hn],
                    marker=mk[net], ls=ls[net], color="black", ms=3.2, lw=0.8, zorder=3,
                    label=f"{NET_TITLE[net]} {c.hw_name}")
            rows += [{"panel": "latency", "net": net, "clock_mhz": fnum(r["clock_readback_mhz"]),
                      "value": fnum(r["latency_us"]), "unit": "us", "kind": "hw", "src": f"{r['_file']}:{r['_line']}"}
                     for r in hn]
    if not hwr:
        art.placeholder("B2 latency: hw_b2_clock.csv (source=hw)")
    ax.set_ylim(bottom=0)
    ax.set_title("PL latency (µs)", fontsize=FS - 1, pad=3)
    for ax, col, title, unit in ((axs[1], "accel_dp_w", "ΔP SOM rail (W)", "W"),
                                 (axs[2], "accel_energy_per_image_mj", "energy/image (mJ)", "mJ")):
        any_pt = False
        for net in NETS:
            en = sorted([e for e in ents if e["net"] == net and e["mean"].get(col)], key=lambda e: fnum(e["clock"]))
            if not en:
                continue
            any_pt = True
            xs = [fnum(e["clock"]) for e in en]
            ys = [fnum(e["mean"][col]) for e in en]
            es = [fnum(e["std"][col]) if e["std"] is not None and e["std"].get(col) else 0.0 for e in en]
            ax.errorbar(xs, ys, yerr=es, marker=mk[net], ls=ls[net], color="black", ms=3.2, lw=0.8, capsize=1.5,
                        elinewidth=0.6, zorder=3, label=f"{NET_TITLE[net]} {c.hw_name}")
            rows += [{"panel": col, "net": net, "clock_mhz": x, "value": y, "unit": unit, "kind": "hw INA260 mean",
                      "std": s, "src": f"{e['mean']['_file']}:{e['mean']['_line']}"} for x, y, s, e in zip(xs, ys, es, en)]
        if not any_pt:
            art.placeholder(f"B2 {col}: hw_b2_power_ina260_summary*.csv (source=hw)")
            ax.add_patch(Rectangle((0, 0), 1, 1, transform=ax.transAxes, fill=False, lw=0.5, edgecolor="0.55",
                                   hatch="////", linestyle=(0, (2, 1.5))))
            ax.text(0.5, 0.5, "board data\npending", transform=ax.transAxes, ha="center", va="center",
                    fontsize=FS - 1.5, style="italic", color="0.2",
                    bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="0.55", lw=0.5, ls="--"))
            ax.set_yticks([])
        else:
            ax.set_ylim(bottom=0)
        ax.set_title(title, fontsize=FS - 1, pad=3)
    for ax in axs:
        ax.yaxis.grid(True, color="0.88", lw=0.4, zorder=0)
        ax.tick_params(labelsize=FS - 2)
    if not hwr:
        axs[0].text(0.5, 0.97, "board pending", transform=axs[0].transAxes, ha="center", va="top",
                    fontsize=FS - 2, style="italic", color="0.3")
    axs[1].set_xlabel("pl_clk0 (MHz)", fontsize=FS - 1)
    h, l = axs[0].get_legend_handles_labels()
    h2, l2 = axs[2].get_legend_handles_labels()
    seen = dict(zip(l + l2, h + h2))
    if seen:
        fig.legend(list(seen.values()), list(seen.keys()), loc="outside lower center", ncol=2, fontsize=FS - 2,
                   handletextpad=0.3, columnspacing=0.8)
    fig.suptitle(f"\u0394P and energy/image: {INA_LABEL}", fontsize=FS - 1.5, color="0.25")
    return c.save(art, fig, rows)


