# A4: MAC_ACTIVE / cycles and theoretical PE utilization per layer
# --------------------------------------------------------------------------------------------
def fig_a4(c: FCtx) -> Artifact:
    art = c.art("fig_a4_util")
    data = {net: a3_net(art, net) for net in NETS}
    nets = [n for n in NETS if data[n]]
    fig, axs = plt.subplots(1, len(nets), figsize=(COL_W, 2.3), sharey=True, layout="constrained",
                            gridspec_kw=dict(width_ratios=[len(data[n]) for n in nets]))
    axs = list(axs) if len(nets) > 1 else [axs]
    rows, any_hw = [], False
    w = 0.26
    for ax, net in zip(axs, nets):
        hw = latest(art.rows("hw_a4_util.csv", hw=True, net=net) or [], lambda r: r["layer"])
        for i, x in enumerate(data[net]):
            am = div(x["mac_model"], x["model"], "MAC_ACTIVE/cycles").value * 100
            ut = x["util_th"].value * 100
            h = hw.get(x["layer"])
            ax.bar(i - w, am, w, lw=0.5, zorder=3, **ST_MODEL)
            ax.bar(i, ut, w, lw=0.5, zorder=3, facecolor="0.8", edgecolor="black", hatch="\\\\\\\\")
            if h and h.get("active_frac"):
                any_hw = True
                ax.bar(i + w, fnum(h["active_frac"]) * 100, w, lw=0.5, zorder=3, **ST_HW)
            else:
                art.placeholder(f"A4 {net} {x['layer']}: hw_a4_util.csv")
                _placeholder_box(ax, i + w / 2, w)
            rows.append({"net": net, "layer": x["layer"], "mac_active_over_cycles_pct_model": am,
                         "pe_util_theoretical_pct": ut,
                         "hw_active_frac_pct": fnum(h["active_frac"]) * 100 if h and h.get("active_frac") else "",
                         "src": f"{x['mac_model'].origin}; {x['model'].origin}; {x['util_th'].origin}"})
        ax.set_xticks(range(len(data[net])))
        ax.set_xticklabels(["total" if x["is_total"] else art.label(x["layer"], "cycle_model.csv:layer")
                            for x in data[net]], rotation=35, ha="right", rotation_mode="anchor")
        ax.set_title(NET_TITLE.get(net, net), loc="left", fontsize=FS, weight="bold", pad=2)
        ax.set_ylim(0, 100)
        ax.yaxis.grid(True, color="0.88", lw=0.4, zorder=0)
    axs[0].set_ylabel("%")
    handles = [Patch(lw=0.5, label="MAC-active cycles (model)", **ST_MODEL),
               Patch(lw=0.5, label="PE utilization (model)", facecolor="0.8", edgecolor="black", hatch="\\\\\\\\"),
               Patch(lw=0.5, label=c.hw_name, **ST_HW) if any_hw else
               Patch(lw=0.5, label="KV260: board data pending", fill=False,
                     **{k: v for k, v in ST_PH.items() if k != "facecolor"})]
    fig.legend(handles=handles, ncol=2, loc="outside lower center", handlelength=1.4,
               columnspacing=0.8)
    return c.save(art, fig, rows)


