# A3: three-way per-layer cycle agreement (priority figure)
# --------------------------------------------------------------------------------------------
def _a3_panel(ax, art: Artifact, net: str, d: list[dict], hw_name: str, show_ylabel=True, ann_fs=FS - 1,
              row_labels=True):
    n = len(d)
    w = 0.26
    xs = list(range(n))
    has_hw = any(x["hw"] is not None for x in d)
    for i, x in enumerate(d):
        xi = i + (0.35 if x["is_total"] else 0.0)
        xs[i] = xi
        ax.bar(xi - w, x["model"].value, w, lw=0.5, zorder=3, **ST_MODEL)
        if x["rtl"] is not None:
            ax.bar(xi, x["rtl"].value, w, lw=0.5, zorder=3, **ST_RTL)
        if x["hw"] is not None:
            ax.bar(xi + w, x["hw"].value, w, lw=0.5, zorder=3, **ST_HW)
        else:
            art.placeholder(f"A3 {net} {x['layer']}: hw_a2_a3_cycles.csv (source=hw)")
            _placeholder_box(ax, xi + w / 2, w)
    ax.set_yscale("log")
    lo = min(x["model"].value for x in d)
    hi = max(max(x["model"].value, (x["rtl"] or x["model"]).value, (x["hw"] or x["model"]).value) for x in d)
    ax.set_ylim(lo / 2.2, hi * 2.2)
    ax.set_xlim(-0.6, xs[-1] + 0.6)
    ax.set_xticks(xs)
    ax.set_xticklabels([("total" if x["is_total"] else art.label(x["layer"], "cycle_model.csv:layer")) for x in d])
    if d[-1]["is_total"]:
        ax.axvline((xs[-2] + xs[-1]) / 2, color="0.6", lw=0.5, ls=":", zorder=0)
    ax.yaxis.grid(True, which="major", color="0.88", lw=0.4, zorder=0)
    if show_ylabel:
        ax.set_ylabel("cycles (log)")
    # per-layer error annotations (computed from the CSV values), two rows above the plot area
    tr = blended_transform_factory(ax.transData, ax.transAxes)
    for xi, x in zip(xs, d):
        r = x["rtl_err"].fmt(art, "pct2") if x["rtl_err"] is not None else "n/a"
        ax.text(xi, 1.13, r.replace("$-$", "−") + "%", transform=tr, ha="center", va="bottom",
                fontsize=ann_fs, color="0.15")
        h = (x["hw_err"].fmt(art, "pct2").replace("$-$", "−") + "%") if x["hw_err"] is not None else "TBD"
        ax.text(xi, 1.02, h, transform=tr, ha="center", va="bottom", fontsize=ann_fs,
                color="0.15" if x["hw_err"] is not None else "0.45",
                style="normal" if x["hw_err"] is not None else "italic")
    if row_labels:
        ax.text(-0.01, 1.13, "RTL vs model:", transform=ax.transAxes, ha="right", va="bottom", fontsize=ann_fs)
        ax.text(-0.01, 1.02, "KV260 vs model:", transform=ax.transAxes, ha="right", va="bottom",
                fontsize=ann_fs)
    ax.set_title(NET_TITLE.get(net, net), loc="center", pad=27, fontsize=FS, weight="bold")
    return has_hw


def _a3_legend(fig, hw_name, has_hw, **kw):
    handles = [Patch(lw=0.5, label="model (analytical)", **ST_MODEL),
               Patch(lw=0.5, label="RTL sim (xsim)", **ST_RTL),
               Patch(lw=0.5, label=hw_name, **ST_HW) if has_hw else
               Patch(lw=0.5, label="KV260: board data pending", fill=False,
                     **{k: v for k, v in ST_PH.items() if k != "facecolor"})]
    fig.legend(handles=handles, ncol=3, handlelength=1.4, columnspacing=1.0, handletextpad=0.4, **kw)


def fig_a3(c: FCtx, wide: bool) -> Artifact:
    art = c.art("fig_a3_cycles_wide" if wide else "fig_a3_cycles")
    data = {net: a3_net(art, net) for net in NETS}
    nets = [n for n in NETS if data[n]]
    if wide:
        fig, axs = plt.subplots(1, len(nets), figsize=(DCOL_W, 2.45), layout="constrained",
                                gridspec_kw=dict(width_ratios=[len(data[n]) for n in nets]))
    else:
        fig, axs = plt.subplots(len(nets), 1, figsize=(COL_W, 4.0), layout="constrained")
        fig.get_layout_engine().set(hspace=0.06)
    axs = list(axs) if len(nets) > 1 else [axs]
    has_hw = False
    for i, (ax, net) in enumerate(zip(axs, nets)):
        has_hw |= _a3_panel(ax, art, net, data[net], c.hw_name, show_ylabel=(i == 0 or not wide),
                            row_labels=(i == 0 or not wide))
    if wide:
        _a3_legend(fig, c.hw_name, has_hw, loc="outside lower center")
    else:
        _a3_legend(fig, c.hw_name, has_hw, loc="outside lower center")
    rows = []
    for net in nets:
        for x in data[net]:
            rows.append({"net": net, "layer": x["layer"], "model_cycles": x["model"].value,
                         "rtl_cycles": x["rtl"].value if x["rtl"] else "",
                         "hw_cycles": x["hw"].value if x["hw"] else "",
                         "rtl_err_pct": x["rtl_err"].value if x["rtl_err"] else "",
                         "hw_err_pct": x["hw_err"].value if x["hw_err"] else "",
                         "model_src": x["model"].origin, "rtl_src": x["rtl"].origin if x["rtl"] else "",
                         "hw_src": x["hw"].origin if x["hw"] else "board data pending"})
    return c.save(art, fig, rows)


