"""Figure generators (PDF, IEEEtran column widths, 8-pt text, grayscale + hatching)."""
from __future__ import annotations

import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Patch, Rectangle  # noqa: E402
from matplotlib.transforms import blended_transform_factory  # noqa: E402

from paperdata import INA_LABEL, a3_net, at, div, impl_variants, latest, power_summaries  # noqa: E402
from paperlib import DRYRUN_MARK, NETS, Artifact, Store, _rel, fnum  # noqa: E402

COL_W, DCOL_W = 3.5, 7.16           # IEEEtran single / double column (in)
FS = 8
# grayscale encodings (fill, edge, hatch) -- distinguishable in print without colour
ST_MODEL = dict(facecolor="white", edgecolor="black", hatch="")
ST_RTL = dict(facecolor="0.55", edgecolor="black", hatch="")
ST_HW = dict(facecolor="black", edgecolor="black", hatch="")
ST_PH = dict(facecolor="none", edgecolor="0.55", hatch="////", linestyle=(0, (2, 1.5)))
NET_TITLE = {"lenet5": "LeNet-5", "cifar10": "CIFAR-10"}


def style():
    plt.rcParams.update({
        "font.family": "serif", "font.serif": ["STIXGeneral", "DejaVu Serif"], "mathtext.fontset": "stix",
        "font.size": FS, "axes.labelsize": FS, "axes.titlesize": FS, "xtick.labelsize": FS - 1,
        "ytick.labelsize": FS - 1, "legend.fontsize": FS - 1, "axes.linewidth": 0.6,
        "xtick.major.width": 0.5, "ytick.major.width": 0.5, "xtick.major.size": 2.5, "ytick.major.size": 2.5,
        "ytick.minor.size": 1.5, "ytick.minor.width": 0.4, "hatch.linewidth": 0.5, "hatch.color": "0.55",
        "pdf.fonttype": 42, "ps.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False,
        "legend.frameon": False, "savefig.dpi": 600,
    })


class FCtx:
    def __init__(self, store: Store, out: Path, dryrun: bool):
        self.store, self.out, self.dryrun = store, out, dryrun

    def art(self, name):
        return Artifact(self.store, name, "figure")

    @property
    def hw_name(self):
        return "KV260 (DRY RUN)" if self.dryrun else "KV260 (measured)"

    def save(self, art: Artifact, fig, data_rows: list[dict]):
        if self.dryrun:
            fig.text(0.5, 0.5, DRYRUN_MARK, ha="center", va="center", rotation=25, fontsize=22,
                     color="0.3", alpha=0.35, weight="bold", zorder=100)
        p = self.out / f"{art.name}.pdf"
        p.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(p,
                    metadata={"CreationDate": None, "ModDate": None,
                              "Subject": "generated by v2/paper/scripts/make_all.py; see MANIFEST.json"})
        plt.close(fig)
        art.outputs.append(_rel(p))
        if data_rows:                                   # the plotted numbers, for review
            q = self.out / f"{art.name}.data.csv"
            with open(q, "w", newline="") as f:
                w = csv.DictWriter(f, fieldnames=list(dict.fromkeys(k for r in data_rows for k in r)))
                w.writeheader()
                w.writerows(data_rows)
            art.outputs.append(_rel(q))
        return art


def _placeholder_box(ax, x0, width, trans_y=True):
    """Hatched outline spanning the whole axis height at x0..x0+width: never a data value."""
    tr = blended_transform_factory(ax.transData, ax.transAxes)
    ax.add_patch(Rectangle((x0, 0.0), width, 1.0, transform=tr, fill=False, lw=0.5, zorder=1, **{
        k: v for k, v in ST_PH.items() if k != "facecolor"}))


def _pending_label(ax, text="board data pending"):
    ax.text(0.99, 0.97, text, transform=ax.transAxes, ha="right", va="top", fontsize=FS - 1, style="italic",
            color="0.2", bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="0.55", lw=0.5, ls="--"), zorder=50)


